import type { FastifyInstance } from "fastify";
import type { SimulationSpec } from "@txloom/spec";
import { ENGINE_VERSION } from "@txloom/engine";
import { getDb } from "../db/knex.js";
import { RunRepository, RunPartitionRepository } from "../db/repositories/runs.js";
import { getQueues } from "../services/queues.js";
import { PARTITION_JOB_OPTIONS } from "../services/run-launch-service.js";
import { RunDeliveryRepository, serializeDelivery } from "../db/repositories/run-deliveries.js";
import { deliverPayloadFor, enqueueDelivery } from "../services/delivery-service.js";

/**
 * Run control: pause/resume/cancel. Generation granularity is per-partition
 * (not per-day), so pause/cancel act on not-yet-started partitions — an
 * already-executing partition finishes (regeneration is idempotent, D7, so
 * this never duplicates or corrupts output). Resume re-enqueues every
 * partition not yet `done`, exactly like idempotent crash resume (T096).
 */
export default async function runControlRoutes(app: FastifyInstance) {
  const db = getDb();
  const runs = new RunRepository(db);
  const runPartitions = new RunPartitionRepository(db);
  const deliveries = new RunDeliveryRepository(db);
  const dataDir = process.env.DATA_DIR ?? "./data";

  async function removePendingJobs(runId: string): Promise<void> {
    const partitions = await runPartitions.listByRun(runId);
    const queues = getQueues();
    for (const partition of partitions) {
      if (partition.state !== "pending") continue;
      const job = await queues.generatePartition.getJob(`${runId}-${partition.partition_no}`);
      await job?.remove();
    }
  }

  function engineMismatch(runEngineVersion: number, action: string) {
    return {
      error: {
        code: "engine_version_mismatch",
        message: `Run was generated by engine version ${runEngineVersion}; this install is version ${ENGINE_VERSION}. ${action}`,
        details: { run_engine_version: runEngineVersion, current_engine_version: ENGINE_VERSION },
      },
    };
  }

  /** Re-enqueues every partition that isn't `done`. Generation is idempotent (same seed and
   * spec rewrite the same files), so re-running an interrupted partition is always safe. */
  async function enqueueUnfinished(
    run: NonNullable<Awaited<ReturnType<RunRepository["getById"]>>>,
    jobName: string,
    jobIdSuffix: string,
  ): Promise<void> {
    const spec = run.spec_snapshot as SimulationSpec;
    const queues = getQueues();
    for (const partition of await runPartitions.listByRun(run.id)) {
      if (partition.state === "done") continue;
      if (partition.state === "failed") {
        await runPartitions.setState(run.id, partition.partition_no, "pending");
      }
      await queues.generatePartition.add(
        `${jobName}-${run.id}-${partition.partition_no}`,
        {
          runId: run.id,
          spec,
          seed: run.seed,
          partitionNo: partition.partition_no,
          partitionCount: run.partition_count,
          engineVersion: run.engine_version,
          dataDir,
        },
        { jobId: `${run.id}-${partition.partition_no}${jobIdSuffix}`, ...PARTITION_JOB_OPTIONS },
      );
    }
  }

  app.post("/runs/:id/pause", async (request, reply) => {
    const { id } = request.params as { id: string };
    const run = await runs.getById(id);
    if (!run) {
      reply.status(404);
      return { error: { code: "not_found", message: `Run "${id}" not found` } };
    }
    if (run.status !== "running") {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message: `Run is "${run.status}", not "running" — cannot pause.`,
        },
      };
    }

    await removePendingJobs(id);
    await runs.setStatus(id, "paused");
    return runs.getById(id);
  });

  app.post("/runs/:id/resume", async (request, reply) => {
    const { id } = request.params as { id: string };
    const run = await runs.getById(id);
    if (!run) {
      reply.status(404);
      return { error: { code: "not_found", message: `Run "${id}" not found` } };
    }
    if (run.status !== "paused") {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message: `Run is "${run.status}", not "paused" — cannot resume.`,
        },
      };
    }

    if (run.engine_version !== ENGINE_VERSION) {
      reply.status(409);
      return engineMismatch(
        run.engine_version,
        "Resuming would mix outputs from two engines — regenerate the run instead.",
      );
    }

    await enqueueUnfinished(run, "resume", "");
    await runs.setStatus(id, "running");
    return runs.getById(id);
  });

  app.post("/runs/:id/retry", async (request, reply) => {
    const { id } = request.params as { id: string };
    const run = await runs.getById(id);
    if (!run) {
      reply.status(404);
      return { error: { code: "not_found", message: `Run "${id}" not found` } };
    }
    if (run.status !== "failed") {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message: `Run is "${run.status}", not "failed" — only a failed run can be retried.`,
        },
      };
    }
    if (run.engine_version !== ENGINE_VERSION) {
      reply.status(409);
      return engineMismatch(
        run.engine_version,
        "Retrying would mix outputs from two engines — regenerate the run instead.",
      );
    }

    const retryCount = await runs.incrementRetryCount(id);
    await enqueueUnfinished(run, "retry", `-r${retryCount}`);
    await runs.setStatus(id, "running");
    return runs.getById(id);
  });

  /** A failed history replay waits for a decision (FR-021): retry it from its cursor, or skip it. */
  async function failedDelivery(
    runId: string,
    sink: string,
    reply: { status: (code: number) => unknown },
  ) {
    const run = await runs.getById(runId);
    const delivery = run ? await deliveries.get(runId, sink) : undefined;
    if (!run || !delivery) {
      reply.status(404);
      return {
        error: {
          code: "not_found",
          message: `Run "${runId}" has no history replay for sink "${sink}"`,
        },
      } as const;
    }
    if (delivery.state !== "failed") {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message: `The replay to "${sink}" is "${delivery.state}", not "failed".`,
        },
      } as const;
    }
    return { run, delivery } as const;
  }

  app.post("/runs/:id/deliveries/:sink/retry", async (request, reply) => {
    const { id, sink } = request.params as { id: string; sink: string };
    const found = await failedDelivery(id, sink, reply);
    if ("error" in found) return found;
    if (found.run.engine_version !== ENGINE_VERSION) {
      reply.status(409);
      return engineMismatch(
        found.run.engine_version,
        "Replaying would mix outputs from two engines — regenerate the run instead.",
      );
    }
    const payload = await deliverPayloadFor(db, found.run, sink, dataDir);
    if (!payload) {
      reply.status(409);
      return {
        error: {
          code: "destination_connection_missing",
          message: `Sink "${sink}" has no destination connection to replay to.`,
          details: { sink },
        },
      };
    }
    await deliveries.markRunning(id, sink);
    await enqueueDelivery(payload, Date.now());
    return serializeDelivery((await deliveries.get(id, sink))!);
  });

  app.post("/runs/:id/deliveries/:sink/skip", async (request, reply) => {
    const { id, sink } = request.params as { id: string; sink: string };
    const found = await failedDelivery(id, sink, reply);
    if ("error" in found) return found;
    await deliveries.setState(id, sink, "skipped");
    return serializeDelivery((await deliveries.get(id, sink))!);
  });

  app.post("/runs/:id/cancel", async (request, reply) => {
    const { id } = request.params as { id: string };
    const run = await runs.getById(id);
    if (!run) {
      reply.status(404);
      return { error: { code: "not_found", message: `Run "${id}" not found` } };
    }
    if (run.status === "completed" || run.status === "cancelled") {
      reply.status(409);
      return { error: { code: "invalid_state", message: `Run is already "${run.status}".` } };
    }

    await removePendingJobs(id);
    await runs.setStatus(id, "cancelled");
    return runs.getById(id);
  });
}
