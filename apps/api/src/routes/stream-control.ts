import type { FastifyInstance, FastifyReply } from "fastify";
import type { SimulationSpec } from "@txloom/spec";
import { ENGINE_VERSION } from "@txloom/engine";
import { getDb } from "../db/knex.js";
import { RunRepository } from "../db/repositories/runs.js";
import {
  StreamRepository,
  streamDestinations,
  type StreamRow,
} from "../db/repositories/streams.js";
import {
  StreamSessionRepository,
  type SessionDestination,
} from "../db/repositories/stream-sessions.js";
import { RunDeliveryRepository } from "../db/repositories/run-deliveries.js";
import { validateDestinations, type DestinationInput } from "../services/destinations.js";
import { ConnectionRepository } from "../db/repositories/connections.js";
import { RunDestinationRepository } from "../db/repositories/run-destinations.js";
import {
  createStreamSession,
  DEFAULT_MAX_STREAMS,
  launchSessionDestinations,
} from "../services/stream-sessions.js";

interface StreamStartBody {
  target_tps?: number;
  label_channel_enabled?: boolean;
  /** Removed — destinations come from the run's `run_destinations` (US1). */
  sink?: unknown;
}

interface StreamRateBody {
  target_tps: number;
}

/**
 * Stream lifecycle (FR-028/029/030): `POST .../stream/start|pause|resume|stop`,
 * `PATCH .../stream` for live rate changes, `GET .../stream` for state +
 * metrics. Continuity with the history phase (FR-029) comes from the
 * `stream-drive` job resuming the same world via `resumeLiveWorld` — this
 * route's only job is to snapshot the run's spec/seed into the job payload
 * and drive the `streams` row's state machine
 * (`idle → streaming ⇄ paused → stopped`); pause/resume never touch the job
 * itself, so its in-memory world state survives a pause untouched.
 *
 * Destinations are never supplied here: they are the run's launch-time
 * `run_destinations` rows, each bound to a saved connection. The job payload
 * carries only connection IDs and targets — the worker resolves and decrypts
 * the connection itself, so no secret ever enters Redis.
 */
export default async function streamControlRoutes(app: FastifyInstance) {
  const db = getDb();
  const runs = new RunRepository(db);
  const streams = new StreamRepository(db);
  const runDestinations = new RunDestinationRepository(db);
  const sessions = new StreamSessionRepository(db);
  const dataDir = process.env.DATA_DIR ?? "./data";

  async function deletedLaunchDestination(runId: string) {
    return (await runDestinations.listByRun(runId)).find((d) => d.connection_id === null);
  }

  /** The `Stream` of contracts/api.md: the row, plus every `StreamMetrics` field (zeroed until the
   * worker has reported) flattened beside it. */
  function serialize(stream: StreamRow) {
    const reported = (
      typeof stream.metrics === "string" ? JSON.parse(stream.metrics) : (stream.metrics ?? {})
    ) as Record<string, unknown>;
    return {
      achieved_tps: 0,
      aimd_rate: stream.target_tps,
      sink_lag: 0,
      in_flight: 0,
      retry_queue: 0,
      backpressure: false,
      delivered_total: 0,
      failed_total: 0,
      sim_time: null,
      ...reported,
      ...stream,
      last_error: stream.last_error ?? (reported.last_error as string | null | undefined) ?? null,
      metrics: reported,
      destinations: streamDestinations(stream),
    };
  }

  app.post("/runs/:id/stream/start", async (request, reply) => {
    const { id: runId } = request.params as { id: string };
    const body = (request.body ?? {}) as StreamStartBody;

    if (body.sink !== undefined) {
      reply.status(400);
      return {
        error: {
          code: "inline_sink_removed",
          message:
            "Inline sinks were removed. Create a connection, then choose it as a destination when you launch the run.",
        },
      };
    }

    const run = await runs.getById(runId);
    if (!run) {
      reply.status(404);
      return { error: { code: "not_found", message: `Run "${runId}" not found` } };
    }
    if (run.status !== "completed") {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message: `Run is "${run.status}", not "completed" — the history phase must finish before streaming.`,
        },
      };
    }

    if (run.engine_version !== ENGINE_VERSION) {
      reply.status(409);
      return {
        error: {
          code: "engine_version_mismatch",
          message: `Run was generated by engine version ${run.engine_version}; this install is version ${ENGINE_VERSION}. Streaming would continue a different world than the history phase produced — regenerate the run first.`,
          details: {
            run_engine_version: run.engine_version,
            current_engine_version: ENGINE_VERSION,
          },
        },
      };
    }

    // Live events must not overtake the history: wait for every replay to finish or be skipped.
    if (await new RunDeliveryRepository(db).hasBlocking(runId)) {
      reply.status(409);
      return {
        error: {
          code: "replay_pending",
          message:
            "History replay to the broker is still running, or failed. Wait for it, or retry or skip it, before starting the live stream.",
        },
      };
    }

    const spec = run.spec_snapshot as SimulationSpec;
    const targetTps = body.target_tps ?? spec.clock.then_stream_tps;
    if (!targetTps || targetTps <= 0) {
      reply.status(400);
      return {
        error: {
          code: "invalid_target_tps",
          message: "target_tps must be a positive number (or spec.clock.then_stream_tps set)",
        },
      };
    }
    const stream = await streams.getByRunId(runId);
    if (stream?.state === "paused") {
      reply.status(409);
      return {
        error: {
          code: "stream_paused",
          message: "Stream is paused. Resume it, or stop it first to change the destination.",
        },
      };
    }
    if (stream?.state === "streaming" || stream?.state === "error") {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message:
            stream.state === "error"
              ? "Stream stopped on an error. Stop it, then start it again."
              : "Stream is already streaming.",
        },
      };
    }

    // The stream's own destinations (initialized from the launch record) are what a session
    // uses; every one must still point at a saved connection.
    const destinations: SessionDestination[] = stream
      ? streamDestinations(stream)
      : await launchSessionDestinations(db, runId);
    const connections = new ConnectionRepository(db, dataDir);
    for (const destination of destinations) {
      if (!(await connections.getById(destination.connection_id))) {
        reply.status(409);
        return {
          error: {
            code: "destination_connection_missing",
            message: `Sink "${destination.sink}" points at a connection that has since been deleted. Choose another destination, or recreate the connection.`,
            details: { sink: destination.sink },
          },
        };
      }
    }
    const missingLaunch = stream ? undefined : await deletedLaunchDestination(runId);
    if (missingLaunch) {
      reply.status(409);
      return {
        error: {
          code: "destination_connection_missing",
          message: `Sink "${missingLaunch.sink_name}" was sent to connection "${missingLaunch.connection_name}", which has since been deleted. Recreate the connection and relaunch.`,
          details: { sink: missingLaunch.sink_name },
        },
      };
    }

    const maxStreams = Number(process.env.TXLOOM_MAX_STREAMS) || DEFAULT_MAX_STREAMS;
    if ((await sessions.countActive()) >= maxStreams) {
      reply.status(409);
      return {
        error: {
          code: "stream_limit",
          message: `${maxStreams} streams are already running (TXLOOM_MAX_STREAMS). Stop one, or raise the limit.`,
        },
      };
    }

    const labelChannelEnabled =
      body.label_channel_enabled ?? stream?.label_channel_enabled ?? false;
    const started = await createStreamSession(db, {
      run,
      targetTps,
      labelChannelEnabled,
      destinations,
      stream,
    });
    return serialize(started);
  });

  async function transition(
    runId: string,
    from: readonly StreamRow["state"][],
    to: StreamRow["state"],
    reply: FastifyReply,
  ) {
    const stream = await streams.getByRunId(runId);
    if (!stream) {
      reply.status(404);
      return { error: { code: "not_found", message: `No stream for run "${runId}"` } };
    }
    if (!from.includes(stream.state)) {
      reply.status(409);
      return {
        error: {
          code: "invalid_state",
          message: `Stream is "${stream.state}" — cannot transition to "${to}" from there.`,
        },
      };
    }
    await streams.setState(stream.id, to);
    return serialize((await streams.getById(stream.id))!);
  }

  app.post("/runs/:id/stream/pause", async (request, reply) => {
    const { id } = request.params as { id: string };
    return transition(id, ["streaming"], "paused", reply);
  });

  app.post("/runs/:id/stream/resume", async (request, reply) => {
    const { id } = request.params as { id: string };
    return transition(id, ["paused"], "streaming", reply);
  });

  app.post("/runs/:id/stream/stop", async (request, reply) => {
    const { id } = request.params as { id: string };
    return transition(id, ["streaming", "paused", "error"], "stopped", reply);
  });

  app.patch("/runs/:id/stream", async (request, reply) => {
    const { id: runId } = request.params as { id: string };
    const body = request.body as StreamRateBody;

    const stream = await streams.getByRunId(runId);
    if (!stream) {
      reply.status(404);
      return { error: { code: "not_found", message: `No stream for run "${runId}"` } };
    }
    if (stream.state === "stopped") {
      reply.status(409);
      return {
        error: { code: "invalid_state", message: "Stream is stopped — cannot adjust rate." },
      };
    }
    if (!body.target_tps || body.target_tps <= 0) {
      reply.status(400);
      return {
        error: { code: "invalid_target_tps", message: "target_tps must be a positive number" },
      };
    }

    await streams.setTargetTps(stream.id, body.target_tps);
    return serialize((await streams.getById(stream.id))!);
  });

  /** Changes where future sessions deliver (FR-048). Only the stream's own destinations change:
   * the run's launch record is never rewritten, so it keeps saying where the run was sent. */
  app.put("/runs/:id/stream/destinations", async (request, reply) => {
    const { id: runId } = request.params as { id: string };
    const body = (request.body ?? {}) as { destinations?: DestinationInput[] };
    const run = await runs.getById(runId);
    const stream = await streams.getByRunId(runId);
    if (!run || !stream) {
      reply.status(404);
      return { error: { code: "not_found", message: `No stream for run "${runId}"` } };
    }
    if (stream.state === "streaming" || stream.state === "paused" || stream.state === "error") {
      reply.status(409);
      return {
        error: {
          code: "stream_active",
          message: `Stream is ${stream.state}. Stop it before changing where it delivers.`,
        },
      };
    }
    const inputs = body.destinations ?? [];
    const allConnections = await new ConnectionRepository(db, dataDir).list();
    const invalid = validateDestinations(
      run.spec_snapshot as SimulationSpec,
      inputs,
      allConnections,
    );
    if (invalid) {
      reply.status(400);
      return { error: { code: invalid.code, message: invalid.message, details: invalid.details } };
    }
    await streams.setDestinations(
      stream.id,
      inputs.map((d) => ({
        sink: d.sink,
        connection_id: d.connection_id,
        ...(d.topic ? { topic: d.topic } : {}),
        ...(d.routing_key ? { routing_key: d.routing_key } : {}),
        ...(d.label_topic ? { label_topic: d.label_topic } : {}),
      })),
    );
    return serialize((await streams.getById(stream.id))!);
  });

  app.get("/runs/:id/stream/sessions", async (request, reply) => {
    const { id: runId } = request.params as { id: string };
    const stream = await streams.getByRunId(runId);
    if (!stream) {
      reply.status(404);
      return { error: { code: "not_found", message: `No stream for run "${runId}"` } };
    }
    return { sessions: await sessions.listByStream(stream.id) };
  });

  app.get("/runs/:id/stream", async (request, reply) => {
    const { id: runId } = request.params as { id: string };
    const stream = await streams.getByRunId(runId);
    if (!stream) {
      reply.status(404);
      return { error: { code: "not_found", message: `No stream for run "${runId}"` } };
    }
    const all = await sessions.listByStream(stream.id);
    const current = all.find((session) => session.id === stream.current_session_id) ?? null;
    return { ...serialize(stream), session: current, sessions_count: all.length };
  });
}
